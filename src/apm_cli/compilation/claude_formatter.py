"""CLAUDE.md formatter for Claude Memory integration.

Instructions reach Claude Code through the compiled AGENTS.md output, the
same files every other harness reads (#3939). Each generated CLAUDE.md
imports ``@AGENTS.md`` and, at the root, installed dependency memory, so
both load on every Claude Code version.
"""

import builtins
from dataclasses import dataclass, field
from pathlib import Path

from apm_cli.core.scope import manifest_file

from ..deps.lockfile import resolve_lockfile_path_for_read
from ..primitives.discovery import get_dependency_declaration_order
from ..primitives.models import Chatmode, Instruction, PrimitiveCollection
from ..utils.path_security import ensure_path_within, validate_path_segments
from ..utils.paths import portable_link_relpath, resolve_base_and_source_dirs
from ..version import get_version
from .claude_agents_md import AGENTS_MD_IMPORT
from .constants import BUILD_ID_PLACEHOLDER
from .constitution import read_constitution
from .footer import build_generation_footer
from .link_resolver import UnifiedLinkResolver

# CRITICAL: Shadow Click commands to prevent namespace collision
set = builtins.set
list = builtins.list
dict = builtins.dict


# Header comment for CLAUDE.md files
CLAUDE_HEADER = "<!-- Generated by APM CLI -->"


@dataclass
class ClaudePlacement:
    """Result of CLAUDE.md placement analysis."""

    claude_path: Path
    instructions: builtins.list[Instruction]
    agents: builtins.list[Chatmode] = field(default_factory=list)
    dependencies: builtins.list[str] = field(default_factory=list)  # @import paths
    coverage_patterns: builtins.set[str] = field(default_factory=set)
    source_attribution: builtins.dict[str, str] = field(default_factory=dict)
    is_root: bool = False


@dataclass
class ClaudeCompilationResult:
    """Result of CLAUDE.md compilation."""

    success: bool
    placements: builtins.list[ClaudePlacement]
    content_map: builtins.dict[Path, str]  # claude_path -> content
    warnings: builtins.list[str] = field(default_factory=list)
    errors: builtins.list[str] = field(default_factory=list)
    stats: builtins.dict[str, float] = field(default_factory=dict)


class ClaudeFormatter:
    """Formatter for generating CLAUDE.md files from APM primitives.

    Generates CLAUDE.md files following Claude's Memory format with:
    - an ``@AGENTS.md`` import of the sibling AGENTS.md
    - @import syntax for dependencies

    Note: Agents/workflows are handled separately as .github/agents/ files,
    not included in CLAUDE.md (same as AGENTS.md behavior).
    """

    def __init__(self, base_dir: str = ".", source_dir: str | None = None):
        """Initialize the Claude formatter.

        Args:
            base_dir (str): Base directory for compilation -- where CLAUDE.md
                outputs are written.  Defaults to the current directory.
            source_dir (Optional[str]): Where source primitives and the
                constitution are read from.  Defaults to ``base_dir`` for
                back-compat; set explicitly when ``apm compile --root``
                redirects writes but sources remain in ``$PWD`` so that
                ``<!-- Source: ... -->`` provenance comments render relative
                to the user's working directory rather than the deploy root.
        """
        self.base_dir, self.source_dir = resolve_base_and_source_dirs(base_dir, source_dir)

        self.warnings: builtins.list[str] = []
        self.errors: builtins.list[str] = []
        self.link_resolver = UnifiedLinkResolver(self.source_dir)

    def format_agents_md_imports(
        self,
        primitives: PrimitiveCollection,
        agents_md_paths: builtins.set[Path],
        config: dict | None = None,
    ) -> ClaudeCompilationResult:
        """Format CLAUDE.md files that import their sibling AGENTS.md (#3939).

        Claude Code reads ``AGENTS.md`` natively only while no ``CLAUDE.md``
        counts, and never before v2.1.277. Each generated ``CLAUDE.md``
        imports ``@AGENTS.md`` so the shared output loads on every version:
        the root file always, nested files next to each nested ``AGENTS.md``
        APM writes.

        Args:
            primitives (PrimitiveCollection): Primitives being compiled.
            agents_md_paths (Set[Path]): ``AGENTS.md`` files this compile writes.
            config (Optional[dict]): ``source_attribution`` toggles cosmetic
                annotations; ``include_constitution`` embeds the constitution
                when no generated root ``AGENTS.md`` carries it.

        Returns:
            ClaudeCompilationResult: Result of the CLAUDE.md compilation.
        """
        self.warnings.clear()
        self.errors.clear()

        try:
            config = config or {}
            source_attribution = config.get("source_attribution", False)
            include_constitution = config.get("include_constitution", False)
            self.link_resolver.context_registry.clear()
            self.link_resolver.register_contexts(primitives)

            agents_dirs = {path.parent for path in agents_md_paths}
            dependencies = self._collect_dependencies()
            constitution = include_constitution and bool(read_constitution(self.source_dir))
            placements = []
            if (
                self.base_dir in agents_dirs
                or (self.base_dir / "AGENTS.md").is_file()
                or dependencies
                or constitution
            ):
                placements.append(
                    ClaudePlacement(
                        claude_path=self.base_dir / "CLAUDE.md",
                        instructions=[],
                        dependencies=dependencies,
                        is_root=True,
                    )
                )
            placements.extend(
                ClaudePlacement(claude_path=directory / "CLAUDE.md", instructions=[])
                for directory in sorted(agents_dirs - {self.base_dir})
            )
            content_map = {
                placement.claude_path: self._generate_claude_content(
                    placement,
                    include_constitution=constitution,
                    source_attribution=source_attribution,
                )
                for placement in placements
            }

            return ClaudeCompilationResult(
                success=len(self.errors) == 0,
                placements=placements,
                content_map=content_map,
                warnings=self.warnings.copy(),
                errors=self.errors.copy(),
                stats=self._compile_stats(placements, primitives),
            )

        except Exception as e:
            self.errors.append(f"CLAUDE.md formatting failed: {e!s}")
            return ClaudeCompilationResult(
                success=False,
                placements=[],
                content_map={},
                warnings=self.warnings.copy(),
                errors=self.errors.copy(),
                stats={},
            )

    def _collect_dependencies(self) -> builtins.list[str]:
        """Import installed package-root memory, independent of path depth."""
        installed_root = self.source_dir
        modules_root = installed_root / "apm_modules"
        if not modules_root.exists() and not modules_root.is_symlink():
            installed_root = self.base_dir
            modules_root = installed_root / "apm_modules"
        ensure_path_within(modules_root, installed_root)
        if not modules_root.is_dir():
            return []

        metadata_paths = (
            manifest_file(self.source_dir),
            resolve_lockfile_path_for_read(installed_root, read_only=True),
        )
        if any(path.exists() or path.is_symlink() for path in metadata_paths):
            relative_roots = get_dependency_declaration_order(
                str(self.source_dir), installation_root=installed_root
            )
            package_roots = []
            for relative in relative_roots:
                validate_path_segments(relative, context="installed dependency path")
                package_roots.append(modules_root / relative)
        else:
            # Preserve legacy, metadata-free owner/package trees without guessing
            # that arbitrary deeper documentation directories are packages.
            package_roots = []
            for owner_dir in modules_root.iterdir():
                if owner_dir.name.startswith("."):
                    continue
                ensure_path_within(owner_dir, modules_root)
                if owner_dir.is_dir():
                    package_roots.extend(
                        path for path in owner_dir.iterdir() if not path.name.startswith(".")
                    )

        dependencies: builtins.set[str] = set()
        for package_root in package_roots:
            ensure_path_within(package_root, modules_root)
            claude_path = package_root / "CLAUDE.md"
            ensure_path_within(claude_path, package_root)
            if claude_path.is_file():
                relative = portable_link_relpath(claude_path, self.base_dir)
                if relative is None:
                    raise ValueError(
                        f"Cannot link dependency CLAUDE.md from {modules_root} to "
                        f"{self.base_dir} across filesystem drives. "
                        "Compile to an output directory on the selected module store's drive."
                    )
                dependencies.add(f"@{relative}")
        return sorted(dependencies)

    def _generate_claude_content(
        self,
        placement: ClaudePlacement,
        *,
        include_constitution: bool = False,
        source_attribution: bool = False,
    ) -> str:
        """Generate CLAUDE.md content for a specific placement.

        Args:
            placement (ClaudePlacement): Placement to render.
            include_constitution (bool): Embed the constitution in the root
                file (only when no generated root AGENTS.md carries it).
            source_attribution (bool): Controls the opt-in cosmetic annotations
                only: when True, the APM Version comment and the footer are
                included; when False (default) they are omitted to reduce token
                overhead. CLAUDE_HEADER and Build ID are always emitted
                regardless of this flag: CLAUDE_HEADER is a functional marker
                used by ``apm compile --clean`` to distinguish APM-generated
                files from hand-authored ones (stale-file removal, issue #1729);
                Build ID is always present for drift normalization.

        Returns:
            str: Generated CLAUDE.md content.
        """
        sections = []

        # Header - Build ID and CLAUDE_HEADER are always present.
        # CLAUDE_HEADER is a functional marker used by `apm compile --clean` to
        # distinguish APM-generated files from hand-authored ones (stale-file
        # removal for issue #1729). Build ID is always present for drift
        # normalization. The APM version comment is cosmetic and opt-in.
        sections.append("# CLAUDE.md")
        sections.append(CLAUDE_HEADER)
        sections.append(BUILD_ID_PLACEHOLDER)
        if source_attribution:
            sections.append(f"<!-- APM Version: {get_version()} -->")
        sections.append("")

        # Claude reads the imported AGENTS.md first, then the rest (#3939).
        sections.append(AGENTS_MD_IMPORT)
        sections.append("")

        # Dependencies section (only for root CLAUDE.md)
        if placement.dependencies:
            sections.append("## Dependencies")
            for dep in placement.dependencies:
                sections.append(dep)
            sections.append("")

        if placement.is_root and include_constitution:
            constitution = read_constitution(self.source_dir)
            if constitution:
                sections.append("## Constitution")
                sections.append("")
                sections.append(constitution.strip())
                sections.append("")

        # Footer is opt-in (cosmetic).
        if source_attribution:
            sections.extend(build_generation_footer())

        content = "\n".join(sections)

        # Resolve context/memory links (".context.md", ".memory.md") in the
        # embedded constitution to their actual on-disk location.
        content = self.link_resolver.resolve_links_for_compilation(
            content=content,
            source_file=placement.claude_path.parent,
            compiled_output=placement.claude_path,
        )

        return content

    def _compile_stats(
        self, placements: builtins.list[ClaudePlacement], primitives: PrimitiveCollection
    ) -> builtins.dict[str, float]:
        """Compile statistics about the CLAUDE.md compilation.

        Args:
            placements (List[ClaudePlacement]): Generated placements.
            primitives (PrimitiveCollection): Full primitive collection.

        Returns:
            Dict[str, float]: Compilation statistics.
        """
        total_instructions = sum(len(p.instructions) for p in placements)
        total_patterns = sum(len(p.coverage_patterns) for p in placements)
        total_deps = sum(len(p.dependencies) for p in placements)

        return {
            "claude_files_generated": len(placements),
            "total_instructions_placed": total_instructions,
            "total_patterns_covered": total_patterns,
            "total_dependencies": total_deps,
            "primitives_found": primitives.count(),
        }
