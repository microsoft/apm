"""Deployed native plugin roots and their generated directory marketplace.

Approved plugin roots live in ``<deploy root>/.agents/plugins/<plugin>/``, next
to one generated ``.claude-plugin/marketplace.json``. ``apm_modules`` stays the
source of fetched content; harnesses load only these deployed copies, and each
copy must carry exactly the fingerprint recorded in ``apm.lock.yaml``.
"""

from __future__ import annotations

import json
import os
import shutil
import stat
import uuid
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from pathlib import Path

from apm_cli.utils.atomic_io import atomic_write_text
from apm_cli.utils.content_hash import native_plugin_files
from apm_cli.utils.path_security import ensure_path_within, has_symlink_component, safe_rmtree

from .record import PLUGINS_RELATIVE

CATALOG_RELATIVE = ".claude-plugin/marketplace.json"
CATALOG_OWNER = "APM"
_STAGING = ".apm-staging-"

Fingerprint = Callable[[Path], str]


class NativeLayoutError(RuntimeError):
    """A deployed root or the generated catalog cannot be safely changed."""


def plugins_root(deploy_root: Path) -> Path:
    return Path(deploy_root).absolute() / PLUGINS_RELATIVE


def _checked(root: Path, path: Path) -> Path:
    ensure_path_within(path, root)
    if root.exists() and has_symlink_component(root.parent, path):
        raise NativeLayoutError(f"Refusing to change native plugin state through a symlink: {path}")
    return path


def catalog_plugins(root: Path, marketplace: str) -> frozenset[str]:
    """Return plugin names APM's own generated catalog declares.

    A catalog APM did not generate yields nothing; it is never adopted.
    """
    catalog = _checked(root, root / CATALOG_RELATIVE)
    if not catalog.is_file():
        return frozenset()
    try:
        data = json.loads(catalog.read_text(encoding="utf-8"))
        if data.get("name") != marketplace or data.get("owner") != {"name": CATALOG_OWNER}:
            return frozenset()
        return frozenset(entry["name"] for entry in data["plugins"])
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        return frozenset()


def write_catalog(root: Path, marketplace: str, plugins: Iterable[str], *, owned: bool) -> None:
    """Write the catalog for *plugins*, or remove it when none remain."""
    catalog = _checked(root, root / CATALOG_RELATIVE)
    names = sorted(set(plugins))
    if catalog.exists() and not owned and not catalog_plugins(root, marketplace):
        raise NativeLayoutError(
            f"{catalog} was not generated by APM. Move it aside, then retry; "
            "APM never overwrites a marketplace it did not write."
        )
    if not names:
        if catalog.exists():
            catalog.unlink()
        prune_empty(root)
        return
    document = {
        "name": marketplace,
        "owner": {"name": CATALOG_OWNER},
        "plugins": [{"name": name, "source": f"./{name}"} for name in names],
    }
    catalog.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_text(catalog, json.dumps(document, indent=2) + "\n")


def prune_empty(root: Path) -> None:
    """Remove the catalog directory and plugins root once nothing is left in them."""
    for empty in (root / ".claude-plugin", root):
        if empty.is_dir() and not empty.is_symlink() and not any(empty.iterdir()):
            empty.rmdir()


@dataclass(frozen=True)
class Deployment:
    """Outcome of :func:`deploy_plugin`.

    *replaced* is the previous root, moved aside rather than deleted, so the
    caller can :func:`restore_replaced` it on rollback or
    :func:`discard_replaced` it once the harness settings committed.
    """

    changed: bool
    replaced: Path | None = None


def _owner_only(plugin_root: Path) -> None:
    """Strip group, other and special bits from every file (#1620).

    The fingerprint records only the owner-execute bit, which this keeps, so
    a deployed root's fingerprint is unchanged. Symlinks are never followed.
    """
    for directory, _dirs, files in os.walk(plugin_root, followlinks=False):
        for file_name in files:
            path = Path(directory) / file_name
            if path.is_symlink():
                continue
            mode = stat.S_IMODE(path.stat().st_mode)
            if mode & ~0o700:
                path.chmod(mode & 0o700)


def deploy_plugin(
    root: Path,
    name: str,
    source_root: Path,
    fingerprint: str,
    fingerprint_of: Fingerprint,
    *,
    approved_pin: str | None = None,
    pin_of: Fingerprint | None = None,
) -> Deployment:
    """Make ``root/name`` an exact copy of the approved bytes.

    The staged copy must carry *fingerprint* and, when the plugin was admitted
    by a whole-plugin approval, that approval's *approved_pin* as computed by
    *pin_of*; otherwise nothing at ``root/name`` changes.
    """
    destination = _checked(root, root / name)
    if destination.is_dir() and fingerprint_of(destination) == fingerprint:
        # An unchanged root still meets the permission postcondition, so an
        # upgrade from a copy deployed before #1620's guard is tightened.
        _owner_only(destination)
        return Deployment(False)
    root.mkdir(parents=True, exist_ok=True)
    staging = _checked(root, root / f"{_STAGING}{name}-{uuid.uuid4().hex}")
    replaced: Path | None = None
    try:
        for relative in native_plugin_files(source_root):
            target = staging / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source_root / relative, target)
        _owner_only(staging)
        if fingerprint_of(staging) != fingerprint:
            raise NativeLayoutError(
                f"The copy of {name} does not match its approved fingerprint. Its source in "
                "apm_modules changed during install; run the install again."
            )
        if approved_pin is not None and pin_of is not None and pin_of(staging) != approved_pin:
            raise NativeLayoutError(
                f"The copy of native plugin {name} does not match the content approved with "
                "'apm approve'. Nothing was deployed; review it with 'apm approve --pending' "
                "and approve it again."
            )
        if destination.exists():
            replaced = _checked(root, root / f"{_STAGING}retiring-{name}-{uuid.uuid4().hex}")
            destination.rename(replaced)
        staging.rename(destination)
    finally:
        if staging.exists():
            safe_rmtree(staging, root)
    return Deployment(True, replaced)


def restore_replaced(root: Path, name: str, replaced: Path) -> None:
    """Undo :func:`deploy_plugin`: put the moved-aside root back at ``root/name``."""
    destination = _checked(root, root / name)
    if destination.exists():
        safe_rmtree(destination, root)
    replaced.rename(destination)


def discard_replaced(root: Path, replaced: Path) -> None:
    """Delete a moved-aside root once the new copy is committed."""
    if replaced.exists():
        safe_rmtree(_checked(root, replaced), root)


def retire_plugin(
    root: Path, name: str, fingerprint: str | None, fingerprint_of: Fingerprint
) -> bool:
    """Remove an owned deployed root; keep one whose bytes changed since deploy.

    Returns ``False`` when the root was kept: it differs from *fingerprint*
    (a user edit), cannot be fingerprinted (an unreadable file or a planted
    symlink), or cannot be removed. ``True`` when it is gone.
    """
    destination = _checked(root, root / name)
    if not destination.exists():
        return True
    if fingerprint is not None:
        try:
            if fingerprint_of(destination) != fingerprint:
                return False
        except (OSError, ValueError, RuntimeError):
            return False
    try:
        safe_rmtree(destination, root)
    except OSError:
        return False
    return True
