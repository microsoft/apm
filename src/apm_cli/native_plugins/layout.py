"""Deployed native plugin roots and their generated directory marketplace.

Approved plugin roots live in ``<deploy root>/.agents/plugins/<plugin>/``, next
to one generated ``.claude-plugin/marketplace.json``. ``apm_modules`` stays the
source of fetched content; harnesses load only these deployed copies, and each
copy must carry exactly the fingerprint recorded in ``apm.lock.yaml``.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import stat
import uuid
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from pathlib import Path

from apm_cli.utils.atomic_io import atomic_write_text
from apm_cli.utils.content_hash import native_plugin_files
from apm_cli.utils.path_security import ensure_path_within, has_symlink_component, safe_rmtree

from .record import PLUGINS_RELATIVE

CATALOG_RELATIVE = ".claude-plugin/marketplace.json"
CATALOG_OWNER = "APM"
ATTRIBUTES_RELATIVE = ".gitattributes"
# Committed roots are byte-pinned by apm.lock.yaml: no line-ending conversion.
ATTRIBUTES_TEXT = "# Generated by APM: plugin bytes are pinned in apm.lock.yaml.\n* -text\n"
_STAGING = ".apm-staging-"

Fingerprint = Callable[[Path], str]


class NativeLayoutError(RuntimeError):
    """A deployed root or the generated catalog cannot be safely changed."""


def plugins_root(deploy_root: Path) -> Path:
    return Path(deploy_root).absolute() / PLUGINS_RELATIVE


def _checked(root: Path, path: Path) -> Path:
    ensure_path_within(path, root)
    if root.exists() and has_symlink_component(root.parent, path):
        raise NativeLayoutError(f"Refusing to change native plugin state through a symlink: {path}")
    return path


def catalog_plugins(root: Path, marketplace: str) -> frozenset[str]:
    """Return plugin names APM's own generated catalog declares.

    A catalog APM did not generate yields nothing; it is never adopted.
    """
    catalog = _checked(root, root / CATALOG_RELATIVE)
    if not catalog.is_file():
        return frozenset()
    try:
        data = json.loads(catalog.read_text(encoding="utf-8"))
        if data.get("name") != marketplace or data.get("owner") != {"name": CATALOG_OWNER}:
            return frozenset()
        return frozenset(entry["name"] for entry in data["plugins"])
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        return frozenset()


def write_catalog(root: Path, marketplace: str, plugins: Iterable[str], *, owned: bool) -> None:
    """Write the catalog for *plugins*, or remove it when none remain."""
    catalog = _checked(root, root / CATALOG_RELATIVE)
    names = sorted(set(plugins))
    if catalog.exists() and not owned and not catalog_plugins(root, marketplace):
        raise NativeLayoutError(
            f"{catalog} was not generated by APM. Move it aside, then retry; "
            "APM never overwrites a marketplace it did not write."
        )
    if not names:
        if catalog.exists():
            catalog.unlink()
        write_attributes(root, enabled=False)
        prune_empty(root)
        return
    document = {
        "name": marketplace,
        "owner": {"name": CATALOG_OWNER},
        "plugins": [{"name": name, "source": f"./{name}"} for name in names],
    }
    catalog.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_text(catalog, json.dumps(document, indent=2) + "\n")


_ATTRIBUTE_NAME = re.compile(r"[A-Za-z0-9_.][-A-Za-z0-9_.]*\Z")
_UNIVERSAL = ("*", "**")
_PINS = ("-text", "binary")
_C_ESCAPES = {"a": "\a", "b": "\b", "f": "\f", "n": "\n", "r": "\r", "t": "\t", "v": "\v"}
_C_ESCAPES.update({"\\": "\\", '"': '"'})


def _read_rules(path: Path) -> list[str]:
    """Lines of a ``.gitattributes``; git skips a UTF-8 BOM and never decodes."""
    text = path.read_text(encoding="utf-8", errors="surrogateescape")
    return (text[1:] if text.startswith("\ufeff") else text).splitlines()


def _unquote(line: str) -> tuple[str, str] | None:
    """Git's C-style unquote of a leading pattern; ``None`` on a bad escape."""
    out: list[str] = []
    index = 1
    while index < len(line):
        char = line[index]
        if char == '"':
            return "".join(out), line[index + 1 :]
        if char != "\\":
            out.append(char)
            index += 1
            continue
        escape = line[index + 1 : index + 2]
        octal = line[index + 1 : index + 4]
        if escape in _C_ESCAPES:
            out.append(_C_ESCAPES[escape])
            index += 2
        elif re.fullmatch(r"[0-3][0-7][0-7]", octal):
            out.append(chr(int(octal, 8)))
            index += 4
        else:
            return None
    return None


def _split_rule(line: str) -> tuple[str, list[str]] | None:
    """Split one ``.gitattributes`` line as git does; ``None`` when git ignores it.

    A pattern git cannot unquote is kept verbatim, quotes included, as git
    keeps it. Git drops a whole line whose pattern is negated or whose
    attribute names are invalid.
    """
    line = line.strip()
    if not line or line.startswith("#"):
        return None
    quoted = _unquote(line) if line.startswith('"') else None
    if quoted is None:
        pattern, *tail = line.split(None, 1)
        rest = tail[0] if tail else ""
    else:
        pattern, rest = quoted
    attributes = rest.split()
    if pattern.startswith("!") or not all(
        _ATTRIBUTE_NAME.match(_attribute_name(attribute)) for attribute in attributes
    ):
        return None
    return pattern, attributes


def _attribute_name(attribute: str) -> str:
    """``-text``, ``!text`` and ``text=auto`` all name ``text``."""
    return (attribute[1:] if attribute[0] in "-!" else attribute).split("=", 1)[0]


def _macros(root: Path) -> dict[str, tuple[str, ...]]:
    """Macros the work tree's top-level ``.gitattributes`` defines."""
    macros: dict[str, tuple[str, ...]] = {}
    top = next((path for path in (root, *root.parents) if (path / ".git").exists()), None)
    top_level = None if top is None else top / ATTRIBUTES_RELATIVE
    if top_level is None or not top_level.is_file():
        return macros
    for line in _read_rules(top_level):
        rule = _split_rule(line)
        if rule is not None and rule[0].startswith("[attr]"):
            macros[rule[0][len("[attr]") :]] = tuple(rule[1])
    return macros


def _touching(macros: dict[str, tuple[str, ...]]) -> frozenset[str]:
    """Attribute names that can change ``text``: itself, ``binary``, and macros reaching them."""
    touching = {"text", "binary"}
    grown = True
    while grown:
        grown = False
        for name, attributes in macros.items():
            if name not in touching and any(
                _attribute_name(attribute) in touching for attribute in attributes
            ):
                touching.add(name)
                grown = True
    return frozenset(touching)


def _conversion_reason(lines: Iterable[str], macros: dict[str, tuple[str, ...]]) -> str | None:
    """Say why a ``.gitattributes`` may leave plugin roots open to conversion.

    Later rules win, and once ``text`` is unset neither ``eol`` nor ``crlf``
    converts. The check is deliberately conservative: the roots count as
    pinned only by a literal ``* -text`` (or ``* binary``) whose last word on
    ``text`` no later rule touches, unless a still later rule for the same
    pattern pins it again. Any other ``text`` or ``binary`` state, or a macro
    that reaches one, is a conflict whatever it resolves to.
    """
    pins = ("-text",) if "binary" in macros else _PINS
    touching = _touching(macros)
    pinned = False
    conflicts: dict[str, str] = {}
    for number, line in enumerate(lines, start=1):
        rule = _split_rule(line)
        if rule is None or rule[0].startswith("[attr]"):
            continue
        pattern, attributes = rule
        last = [attribute for attribute in attributes if _attribute_name(attribute) in touching]
        if not last:
            continue
        conflicts.pop(pattern, None)
        if last[-1] in pins and pattern in _UNIVERSAL:
            pinned = True
            conflicts.clear()
        elif last[-1] not in pins:
            conflicts[pattern] = (
                f"has rule '{line.strip()}' (line {number}), "
                "which can re-enable line-ending conversion"
            )
    if conflicts:
        return next(reversed(conflicts.values()))
    return None if pinned else "has no '* -text' rule"


def _require_pinning(root: Path, attributes: Path) -> None:
    """Refuse a user's file that lets git convert the byte-pinned roots (#4809)."""
    reason = _conversion_reason(_read_rules(attributes), _macros(root))
    if reason is not None:
        raise NativeLayoutError(
            f"{attributes} {reason}, so a checkout with core.autocrlf would change plugin "
            "bytes pinned in apm.lock.yaml. Add '* -text' as its last rule, or delete the "
            "file so APM writes its own, then retry."
        )


def write_attributes(root: Path, *, enabled: bool) -> None:
    """Keep git from converting line endings in committed plugin roots.

    A checkout with ``core.autocrlf`` would otherwise rewrite the bytes the
    lock pins. Only APM's own file is written or removed; a user's is kept,
    but only when it leaves the roots unconverted.
    """
    attributes = _checked(root, root / ATTRIBUTES_RELATIVE)
    ours = attributes.is_file() and attributes.read_bytes() == ATTRIBUTES_TEXT.encode()
    if enabled and not attributes.exists():
        atomic_write_text(attributes, ATTRIBUTES_TEXT)
    elif enabled and not ours:
        _require_pinning(root, attributes)
    elif not enabled and ours:
        attributes.unlink()


def attributes_enabled(root: Path) -> bool:
    """Whether APM's own ``.gitattributes`` is in place, for a rollback to restore."""
    attributes = _checked(root, root / ATTRIBUTES_RELATIVE)
    return attributes.is_file() and attributes.read_text(encoding="utf-8") == ATTRIBUTES_TEXT


def prune_empty(root: Path) -> None:
    """Remove the catalog directory and plugins root once nothing is left in them."""
    for empty in (root / ".claude-plugin", root):
        if empty.is_dir() and not empty.is_symlink() and not any(empty.iterdir()):
            empty.rmdir()


@dataclass(frozen=True)
class Deployment:
    """Outcome of :func:`deploy_plugin`.

    *replaced* is the previous root, moved aside rather than deleted, so the
    caller can :func:`restore_replaced` it on rollback or
    :func:`discard_replaced` it once the harness settings committed.
    """

    changed: bool
    replaced: Path | None = None


def _owner_only(plugin_root: Path) -> None:
    """Strip group, other and special bits from every file (#1620).

    The fingerprint records only the owner-execute bit, which this keeps, so
    a deployed root's fingerprint is unchanged. Symlinks are never followed.
    """
    for directory, _dirs, files in os.walk(plugin_root, followlinks=False):
        for file_name in files:
            path = Path(directory) / file_name
            if path.is_symlink():
                continue
            mode = stat.S_IMODE(path.stat().st_mode)
            if mode & ~0o700:
                path.chmod(mode & 0o700)


def deploy_plugin(
    root: Path,
    name: str,
    source_root: Path,
    fingerprint: str,
    fingerprint_of: Fingerprint,
    *,
    approved_pin: str | None = None,
    pin_of: Fingerprint | None = None,
) -> Deployment:
    """Make ``root/name`` an exact copy of the approved bytes.

    The staged copy must carry *fingerprint* and, when the plugin was admitted
    by a whole-plugin approval, that approval's *approved_pin* as computed by
    *pin_of*; otherwise nothing at ``root/name`` changes.
    """
    destination = _checked(root, root / name)
    if destination.is_dir() and fingerprint_of(destination) == fingerprint:
        # An unchanged root still meets the permission postcondition, so an
        # upgrade from a copy deployed before #1620's guard is tightened.
        _owner_only(destination)
        return Deployment(False)
    root.mkdir(parents=True, exist_ok=True)
    staging = _checked(root, root / f"{_STAGING}{name}-{uuid.uuid4().hex}")
    replaced: Path | None = None
    try:
        for relative in native_plugin_files(source_root):
            target = staging / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source_root / relative, target)
        _owner_only(staging)
        if fingerprint_of(staging) != fingerprint:
            raise NativeLayoutError(
                f"The copy of {name} does not match its approved fingerprint. Its source in "
                "apm_modules changed during install; run the install again."
            )
        if approved_pin is not None and pin_of is not None and pin_of(staging) != approved_pin:
            raise NativeLayoutError(
                f"The copy of native plugin {name} does not match the content approved with "
                "'apm approve'. Nothing was deployed; review it with 'apm approve --pending' "
                "and approve it again."
            )
        if destination.exists():
            replaced = _checked(root, root / f"{_STAGING}retiring-{name}-{uuid.uuid4().hex}")
            destination.rename(replaced)
        staging.rename(destination)
    finally:
        if staging.exists():
            safe_rmtree(staging, root)
    return Deployment(True, replaced)


def restore_replaced(root: Path, name: str, replaced: Path) -> None:
    """Undo :func:`deploy_plugin`: put the moved-aside root back at ``root/name``."""
    destination = _checked(root, root / name)
    if destination.exists():
        safe_rmtree(destination, root)
    replaced.rename(destination)


def discard_replaced(root: Path, replaced: Path) -> None:
    """Delete a moved-aside root once the new copy is committed."""
    if replaced.exists():
        safe_rmtree(_checked(root, replaced), root)


def retire_plugin(
    root: Path, name: str, fingerprint: str | None, fingerprint_of: Fingerprint
) -> bool:
    """Remove an owned deployed root; keep one whose bytes changed since deploy.

    Returns ``False`` when the root was kept: it differs from *fingerprint*
    (a user edit), cannot be fingerprinted (an unreadable file or a planted
    symlink), or cannot be removed. ``True`` when it is gone.
    """
    destination = _checked(root, root / name)
    if not destination.exists():
        return True
    if fingerprint is not None:
        try:
            if fingerprint_of(destination) != fingerprint:
                return False
        except (OSError, ValueError, RuntimeError):
            return False
    try:
        safe_rmtree(destination, root)
    except OSError:
        return False
    return True
