"""Compilation remediations clear the state that reported them (#4090, W3: G5).

Each proof induces one reported compilation state on an installed project,
reads the advised command line from what the installed CLI printed, takes the
manual step the advice names, runs exactly the printed command, and re-runs
the reporting command to observe the state is gone.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest

from tests.integration.test_remediation_advice_lifecycle import (
    _INSTALL_ARGS,
    _expect_ok,
    _normalized,
    _printed_command,
    _result_evidence,
    _run,
    _TextProof,
    _unlink,
    _World,
)
from tests.integration.test_required_lifecycle_state_machine import (
    _new_scenario,
    _publish,
    _run_success,
)

pytestmark = [
    pytest.mark.integration,
    pytest.mark.e2e,
    pytest.mark.lifecycle_smoke,
    pytest.mark.requires_apm_binary,
    pytest.mark.requires_e2e_mode,
]

_COMPILE = ("compile",)
_MARKER = "Generated by APM CLI"
_ORPHAN = "docs/AGENTS.md"


def _codex_world(tmp_path: Path, apm_binary_path: Path) -> _World:
    # Codex reads instructions only from AGENTS.md, so compile always writes it.
    scenario = _new_scenario(tmp_path / "remediation", apm_binary_path)
    source = _publish(scenario, "advice-kit", instruction="advice")
    consumer = scenario.consumers.create(
        "advice-consumer", dependencies=(source.dependency,), targets=("codex",)
    )
    _run_success(
        scenario,
        consumer,
        _INSTALL_ARGS,
        environment=source.environment,
        scenario_id="remediation-g5-install",
    )
    return _World(scenario=scenario, source=source, consumer=consumer)


def _compiled_world(tmp_path: Path, apm_binary_path: Path) -> _World:
    world = _codex_world(tmp_path, apm_binary_path)
    compiled = _run(world, _COMPILE, "remediation-g5-compile")
    _expect_ok(world, compiled)
    assert _MARKER in (world.consumer.root / "AGENTS.md").read_text(encoding="utf-8")
    return world


def _hand_author_root_context(world: _World) -> None:
    (world.consumer.root / "AGENTS.md").write_text("# Hand-authored\n", encoding="ascii")


def _root_context_regenerated(world: _World, result) -> None:
    _expect_ok(world, result)
    assert _MARKER in (world.consumer.root / "AGENTS.md").read_text(encoding="utf-8")
    assert "hand-authored file will not be overwritten" not in _normalized(result)


def _copy_generated_agents_file(world: _World) -> None:
    orphan = world.consumer.root / _ORPHAN
    orphan.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(world.consumer.root / "AGENTS.md", orphan)


def _orphan_removed(world: _World, result) -> None:
    _expect_ok(world, result)
    assert not (world.consumer.root / _ORPHAN).exists()
    assert "Orphaned AGENTS.md" not in _normalized(result), _result_evidence(result)


G5_PROOFS: tuple[_TextProof, ...] = (
    _TextProof(
        "hand-authored-output-protected",
        _codex_world,
        _hand_author_root_context,
        lambda _world: _COMPILE,
        0,
        _root_context_regenerated,
        before=_unlink("AGENTS.md"),
    ),
    _TextProof(
        "orphaned-agents-files",
        _compiled_world,
        _copy_generated_agents_file,
        lambda _world: _COMPILE,
        0,
        _orphan_removed,
    ),
)


@pytest.mark.parametrize("proof", G5_PROOFS, ids=lambda proof: proof.remediation_id)
def test_g5_remediation_clears_the_reported_state(
    tmp_path: Path, apm_binary_path: Path, proof: _TextProof
) -> None:
    world = proof.world(tmp_path, apm_binary_path)
    proof.induce(world)

    reported = _run(world, proof.probe(world), "remediation-reported")
    assert reported.returncode == proof.reported_exit, _result_evidence(reported)
    command = _printed_command(reported, proof.remediation_id)
    assert command[0] == "apm"
    values = proof.values(world)
    argv = tuple(values.get(token, token) for token in command[1:])
    assert not any(token.startswith("<") for token in argv), argv

    proof.before(world)
    advised = _run(world, argv, f"remediation-run-{proof.remediation_id}")
    assert advised.returncode == 0, _result_evidence(advised)

    from apm_cli.core.remediation import catalog

    again = _run(world, (proof.reprobe or proof.probe)(world), "remediation-cleared")
    proof.cleared(world, again)
    promise = catalog()[proof.remediation_id].fixes_promise
    advice = f"'{' '.join(command)}' to {promise}"
    assert advice not in _normalized(again), _result_evidence(again)
