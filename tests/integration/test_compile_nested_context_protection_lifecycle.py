"""Compile never overwrites hand-authored nested context files (#3655).

A distributed compile that places output in a directory holding a
hand-authored ``AGENTS.md`` or ``CLAUDE.md`` (no APM marker) retains it and
warns, exactly as for root files. Re-runs, ``--clean`` and ``--dry-run`` leave
it untouched and the layout stays stable; once the user removes the file, the
directory becomes an ordinary APM-generated output again.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from tests.integration._target_compile_kit import Scenario, output, tree_digest, write

pytestmark = [
    pytest.mark.integration,
    pytest.mark.lifecycle_smoke,
    pytest.mark.requires_apm_binary,
]

_USER_FILES = {
    "docs/AGENTS.md": "# Docs agents\n\nHand-authored docs guidance.\n",
    "docs/CLAUDE.md": "# Docs claude\n\nHand-authored docs memory.\n",
}
_MARKERS = ("<!-- Generated by APM CLI", "<!-- Generated by APM CLI -->")


def _seed(project: Path) -> None:
    write(project / "apm.yml", "name: proj\nversion: 1.0.0\ntargets: [codex, claude]\n")
    write(
        project / ".apm/instructions/docs.instructions.md",
        '---\ndescription: docs\napplyTo: "docs/**"\n---\nDocs rule.\n',
    )
    write(
        project / ".apm/instructions/src.instructions.md",
        '---\ndescription: src\napplyTo: "src/**"\n---\nSrc rule.\n',
    )
    write(project / "docs/guide.md", "# Guide\n")
    write(project / "src/main.py", "x = 1\n")
    for relative, text in _USER_FILES.items():
        write(project / relative, text)


def _assert_user_files(project: Path) -> None:
    for relative, text in _USER_FILES.items():
        assert (project / relative).read_text(encoding="ascii") == text, relative


def test_compile_retains_hand_authored_nested_context_files(
    tmp_path: Path, apm_binary_path: Path
) -> None:
    scenario = Scenario.create(tmp_path, apm_binary_path)
    project = scenario.isolated.work_root / "proj"
    _seed(project)

    first = scenario.run("compile", cwd=project)
    text = output(first)
    for relative in _USER_FILES:
        assert f"Protected {relative}: hand-authored file will not be overwritten" in text, text
    _assert_user_files(project)
    generated = (project / "src/AGENTS.md").read_text(encoding="ascii")
    assert "Src rule." in generated and _MARKERS[0] in generated
    assert "Orphaned" not in text
    layout = tree_digest(project)

    # Re-run, --clean and --dry-run: no orphan, no overwrite, no layout churn.
    for args in (("compile",), ("compile", "--clean"), ("compile", "--dry-run")):
        result = scenario.run(*args, cwd=project)
        assert "Orphaned" not in output(result), args
        assert tree_digest(project) == layout, args
    _assert_user_files(project)

    # Generated nested output stays replaceable when its source changes.
    write(
        project / ".apm/instructions/src.instructions.md",
        '---\ndescription: src\napplyTo: "src/**"\n---\nSrc rule v2.\n',
    )
    scenario.run("compile", cwd=project)
    assert "Src rule v2." in (project / "src/AGENTS.md").read_text(encoding="ascii")
    _assert_user_files(project)

    # The user hands the directory back to APM by removing the file.
    (project / "docs/AGENTS.md").unlink()
    scenario.run("compile", cwd=project)
    regenerated = (project / "docs/AGENTS.md").read_text(encoding="ascii")
    assert "Docs rule." in regenerated and _MARKERS[0] in regenerated
    assert (project / "docs/CLAUDE.md").read_text(encoding="ascii") == _USER_FILES["docs/CLAUDE.md"]
    settled = tree_digest(project)
    scenario.run("compile", cwd=project)
    assert tree_digest(project) == settled
