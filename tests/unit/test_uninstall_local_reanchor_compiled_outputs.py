"""The moving-copy check refuses a compiled-output walk it cannot complete (#5097)."""

from __future__ import annotations

import os
import sys
from pathlib import Path

import pytest

from apm_cli.commands.uninstall.local_reanchor import _compiled_output_naming

pytestmark = [pytest.mark.unit, pytest.mark.promise("P-INV-I3", "P-INV-I1")]


def test_a_directory_the_walk_cannot_list_refuses_instead_of_being_skipped(
    tmp_path: Path,
) -> None:
    """os.walk would skip it silently; the check names it so the copy stays."""
    missing = tmp_path / "gone"

    assert _compiled_output_naming(missing, lambda _path: False) is not None


def test_a_walk_with_no_compiled_output_naming_the_copy_lets_it_move(tmp_path: Path) -> None:
    (tmp_path / "AGENTS.md").write_text("# not compiled\n", encoding="utf-8")

    assert _compiled_output_naming(tmp_path, lambda _path: True) is None


_MARKERS = ("<!-- Generated by APM CLI from .apm/ primitives -->",)


@pytest.mark.skipif(not hasattr(os, "mkfifo"), reason="needs FIFOs")
def test_a_fifo_is_checked_on_its_descriptor_and_never_read(tmp_path: Path) -> None:
    from apm_cli.commands.uninstall.local_reanchor import _marked_regular_file

    fifo = tmp_path / "AGENTS.md"
    os.mkfifo(fifo)

    assert _marked_regular_file(fifo, _MARKERS) is None


@pytest.mark.skipif(sys.platform == "win32", reason="symlinks need privileges on Windows")
def test_a_final_link_is_never_followed(tmp_path: Path) -> None:
    from apm_cli.commands.uninstall.local_reanchor import _marked_regular_file

    target = tmp_path / "real.md"
    target.write_text(f"{_MARKERS[0]}\nbody\n", encoding="utf-8")
    (tmp_path / "AGENTS.md").symlink_to(target)

    assert _marked_regular_file(tmp_path / "AGENTS.md", _MARKERS) is None
    assert _marked_regular_file(target, _MARKERS) == target.read_bytes()


def test_a_managed_section_far_into_a_file_is_found_and_read_whole(tmp_path: Path) -> None:
    """The begin marker is searched across chunk boundaries; the whole file is returned."""
    from apm_cli.commands.uninstall.local_reanchor import _marked_regular_file

    agents = tmp_path / "AGENTS.md"
    body = b"x" * ((1 << 16) + 4090) + b"<!-- apm:start -->\nlink\n<!-- apm:end -->\n"
    agents.write_bytes(body)

    assert _marked_regular_file(agents, _MARKERS, b"<!-- apm:start -->") == body
    assert _marked_regular_file(agents, _MARKERS, b"<!-- not:here -->") is None


def test_a_custom_managed_section_marker_is_read_from_the_project_config(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """compilation.agents_md.start_marker comes from the project's apm.yml, not the cwd's."""
    project = tmp_path / "project"
    project.mkdir()
    (project / "apm.yml").write_text(
        "name: p\nversion: 1.0.0\ncompilation:\n  agents_md:\n"
        "    mode: managed_section\n    start_marker: '<!-- team:begin -->'\n"
        "    end_marker: '<!-- team:end -->'\n",
        encoding="utf-8",
    )
    (project / "AGENTS.md").write_text(
        "# Authored\n\n<!-- team:begin -->\n[g](vendor/pkg/g.md)\n<!-- team:end -->\n",
        encoding="utf-8",
    )
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    monkeypatch.chdir(elsewhere)

    assert _compiled_output_naming(project, lambda _path, _data=None: True) == "AGENTS.md"
    (project / "apm.yml").write_text("name: p\nversion: 1.0.0\n", encoding="utf-8")
    assert _compiled_output_naming(project, lambda _path, _data=None: True) is None
