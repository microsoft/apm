"""Write and check the generated obligation list and replay rows (#4099).

Outputs (sorted, ASCII, no time and no randomness):

- ``tests/quality/lifecycle_obligations.json``: every obligation with its
  family, required strength, status and owning lane; ``required`` ones name
  the covering row that witnesses them, ``known-failing`` ones the tracking
  issue, ``baseline`` ones the lane and issue that must discharge them. Mapped
  and removed cells keep their rule chain. ``sha256`` hashes the canonical
  content (the document without that key), which includes the row hashes.
- ``tests/lifecycle/replay/rows/generated_<row id>.yaml``: the covering rows.
"""

from __future__ import annotations

import hashlib
import json
from collections import Counter
from collections.abc import Mapping
from pathlib import Path

import yaml

from tests.lifecycle.generator import covering
from tests.lifecycle.generator.bin_pin import pin_digest
from tests.lifecycle.generator.factors import (
    EXCEPTION_FACTORS,
    FACTORS,
    MODIFIERS,
    compile_staged_targets,
    row_targets,
)
from tests.lifecycle.generator.rules import RULES, U_BIN_CELLS, U_BIN_PIN
from tests.lifecycle.generator.space import Entry, Space, build_space
from tests.lifecycle.generator.witnesses import machine_witnesses, scenario_witnesses

ROOT = Path(__file__).resolve().parents[3]
OBLIGATIONS_PATH = ROOT / "tests" / "quality" / "lifecycle_obligations.json"
ROWS_DIR = ROOT / "tests" / "lifecycle" / "replay" / "rows"
ROW_PREFIX = "generated_"
WITNESS = "tests/lifecycle/replay/test_covering_replay.py::test_covering_row[{}]"
OWN_LANE = "T-5"
LANES = {
    "T-1": "#4095",
    "T-2": "#4096",
    "T-3": "#4097",
    "T-5": "#4099",
    "T-6a": "#4100",
    "T-6b": "#4101",
    "T-6c": "#4102",
    "T-6e": "#4104",
    "T-7b": "#4108",
}
_TRIPLE_LANES = {"T1": "T-1", "T2": "T-1", "T3": "T-2", "T5": "T-2", "T4": "T-3"}
_INVARIANTS = tuple(f"P-INV-I{n}" for n in range(1, 10))
_HEADER = "# Generated by `python -m tests.lifecycle.generator` (#4099). Do not edit.\n"


def lane_for(entry: Entry) -> str:
    """The lane whose instrument discharges an obligation no covering row reaches."""
    cell = entry.cell
    if entry.family in _TRIPLE_LANES:
        return _TRIPLE_LANES[entry.family]
    checks = (
        ("HOSTID" in cell, "T-2"),
        ("MCPOWN" in cell, "T-6a"),
        ("FILEROUTE" in cell, "T-6c"),
        (cell.get("SCOPE") == "user" or "LOCK" in cell or cell.get("DEPLOYED") == "absent", "T-3"),
        (cell.get("GATE") == "denied-dependency" or "NOPOLICY" in cell, "T-7b"),
        (cell.get("DEPLOYED") in ("edited", "unowned", "present-provenance-unknown"), "T-6b"),
        (cell.get("TGT", "").endswith(("widened", "narrowed")), "T-6a"),
        (cell.get("NET") == "offline", "T-6e"),
        ("SRC" in cell or cell.get("OP") in ("marketplace", "bundle-install"), "T-2"),
        ("GATE" in cell or "PRIM" in cell, "T-1"),
    )
    return next((lane for hit, lane in checks if hit), OWN_LANE)


def _row_document(row: covering.Row) -> dict[str, object]:
    promises = list(_INVARIANTS)
    if row.kind == "refusal":
        promises.append("P-LAW-transaction.failed_command_preserves_state")
    else:
        promises.append("P-OWN-executable-item-admission")
    if any("FROZEN" in step.mods or "--frozen" in step.line for step in row.steps):
        promises.append("P-OWN-frozen-install-mutation-eligibility")
    steps: list[object] = []
    for step in row.steps:
        fields: dict[str, object] = {}
        if step.exit is not None:
            fields["exit"] = step.exit
        if step.message is not None:
            fields["message"] = step.message
        if step.cells:
            fields["cells"] = list(step.cells)
            if step.unchanged:
                fields["unchanged"] = list(step.unchanged)
        steps.append({"run": step.line, **fields} if fields else step.line)
    world: dict[str, object] = {
        "packages": list(row.packages),
        "targets": list(row.targets),
        "scope": "project",
    }
    if row.sources:
        world["sources"] = dict(sorted(row.sources.items()))
    setup = next(index for index, step in enumerate(row.steps) if step.essential) + 1
    return {
        "id": row.id,
        "promises": promises,
        "cell": dict(row.cell),
        "world": world,
        "given": steps[:setup],
        "when": steps[setup:],
        "then": {"deployed": "expected"},
        "known_cells": [],
    }


def render_rows(rows: list[covering.Row]) -> dict[str, str]:
    """File name -> YAML text of every covering row."""
    return {
        f"{ROW_PREFIX}{row.id}.yaml": _HEADER
        + yaml.safe_dump(_row_document(row), sort_keys=False, width=100)
        for row in rows
    }


def _counts(space: Space, statuses: Mapping[str, str], lanes: Mapping[str, str], rows) -> dict:
    families = Counter(entry.family for entry in space.obligations.values())
    exception = sum(
        1 for entry in space.obligations.values() if set(entry.cell) & set(EXCEPTION_FACTORS)
    )
    return {
        "raw_candidates": dict(sorted(space.raw.items())),
        "obligations": dict(sorted(families.items())),
        "obligations_total": len(space.obligations),
        "exception_pairs": exception,
        "must_cover": sum(entry.must_cover for entry in space.obligations.values()),
        "mapped": len(space.mapped),
        "mapped_by_rule": dict(
            sorted(Counter(chain[0] for _, chain in space.mapped.values()).items())
        ),
        "removed": len(space.removed),
        "removed_by_rule": dict(
            sorted(Counter(rules[0] for rules in space.removed.values()).items())
        ),
        "status": dict(sorted(Counter(statuses.values()).items())),
        "baseline_by_lane": dict(
            sorted(
                Counter(
                    lanes[key] for key, status in statuses.items() if status == "baseline"
                ).items()
            )
        ),
        "rows": len(rows),
        "row_steps": sum(len(row.steps) for row in rows),
    }


def u_bin_audit(digest: str) -> tuple[dict[str, list[str]], dict[str, dict[str, object]]]:
    """(excluded, reinstated) gate cells of U-BIN for the live pin *digest*.

    The cells are excluded only while *digest* equals the approved U_BIN_PIN;
    otherwise each one is must-cover again (the rule's premise has changed).
    """
    if digest == U_BIN_PIN:
        return {key: ["U-BIN"] for key in U_BIN_CELLS}, {}
    return {}, {key: {"rules": ["U-BIN"], "must_cover": True} for key in U_BIN_CELLS}


def generate() -> tuple[str, dict[str, str]]:
    """(obligation list JSON text, row file name -> YAML text)."""
    space = build_space()
    rows = covering.cover(space.obligations)
    witness = {
        cell: WITNESS.format(row.id) for row in rows for step in row.steps for cell in step.cells
    }
    machines = machine_witnesses(space.obligations)
    scenarios = scenario_witnesses(
        space.obligations, {key: lane_for(entry) for key, entry in space.obligations.items()}
    )
    statuses, lanes, obligations = {}, {}, {}
    for key in sorted(space.obligations):
        entry = space.obligations[key]
        record: dict[str, object] = {"family": entry.family, "strength": entry.strength}
        machine = machines.get(key)
        if key in witness:
            statuses[key], lanes[key] = "required", OWN_LANE
            record["witness"] = witness[key]
        elif machine is not None:
            lanes[key] = machine.lane
            record["witness"] = machine.node
            record["credited_by"] = list(machine.credited_by)
            if machine.tracking:
                statuses[key] = "known-failing"
                record["tracking"] = machine.tracking
            else:
                statuses[key] = "required"
        elif key in scenarios:
            scenario = scenarios[key]
            lanes[key] = scenario.lane
            record["witness"] = scenario.node
            if scenario.tracking:
                statuses[key] = "known-failing"
                record["tracking"] = scenario.tracking
            else:
                statuses[key] = "required"
        else:
            statuses[key], lanes[key] = "baseline", lane_for(entry)
        record.update(status=statuses[key], lane=lanes[key], issue=LANES[lanes[key]])
        if entry.rules:
            record["rules"] = list(entry.rules)
        if entry.must_cover:
            record["must_cover"] = True
        if entry.exit is not None:
            record["exit"] = entry.exit
        obligations[key] = record
    rendered = render_rows(rows)
    single, multi = row_targets()
    digest = pin_digest()
    excluded, reinstated = u_bin_audit(digest)
    document = {
        "schema_version": 1,
        "description": (
            "Lifecycle interaction obligations (#4099): t=2 pairs of OP, SRC, PRIM, SCOPE, LOCK, "
            "DEPLOYED, GATE, TGT, NET and the modifiers, the exception factors crossed with the "
            "factors they refine, and the named triples T1-T5, after the refusal, definition and "
            "partial-equivalence rules of tests/lifecycle/generator/rules.py. required ids are "
            "credited by oracles.check_obligation in their witness (a covering row, or a machine "
            "spine whose credited_by ids imply the cell); known-failing ids name the strict known "
            "cell's tracking issue; baseline ids "
            "name the lane and issue that must discharge them. Regenerate with "
            "`python -m tests.lifecycle.generator`; `--check` fails on drift."
        ),
        "generator": "python -m tests.lifecycle.generator",
        "lanes": LANES,
        "factors": {
            name: list(values) for name, values in FACTORS.items() if name not in MODIFIERS
        },
        "modifiers": list(MODIFIERS),
        "exception_factors": {name: list(values) for name, values in EXCEPTION_FACTORS.items()},
        "parameters": {
            "compile_staged_targets": list(compile_staged_targets()),
            "row_targets": {"single": list(single), "multi": list(multi)},
        },
        "rules": {
            rule: {"text": text, "evidence": [str(item) for item in evidence]}
            for rule, (text, evidence) in sorted(RULES.items())
        },
        "counts": _counts(space, statuses, lanes, rows),
        "rows": {
            name: hashlib.sha256(text.encode("ascii")).hexdigest()
            for name, text in sorted(rendered.items())
        },
        "obligations": obligations,
        "mapped": {
            key: {"maps_to": target, "rules": list(chain)}
            for key, (target, chain) in sorted(space.mapped.items())
        },
        "removed": {key: list(rules) for key, rules in sorted(space.removed.items())},
        "pins": {"U-BIN": digest},
        "excluded": excluded,
        "reinstated": reinstated,
    }
    canonical = json.dumps(document, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    document["sha256"] = hashlib.sha256(canonical.encode("ascii")).hexdigest()
    text = json.dumps(document, indent=1, sort_keys=True, ensure_ascii=True) + "\n"
    return text, rendered


def drift() -> list[str]:
    """Paths whose checked-in content differs from a fresh generation."""
    text, rows = generate()
    problems = []
    if not OBLIGATIONS_PATH.is_file() or OBLIGATIONS_PATH.read_text(encoding="ascii") != text:
        problems.append(OBLIGATIONS_PATH.relative_to(ROOT).as_posix())
    present = {path.name for path in ROWS_DIR.glob(f"{ROW_PREFIX}*.yaml")}
    for name in sorted(present | set(rows)):
        path = ROWS_DIR / name
        if (
            name not in rows
            or name not in present
            or path.read_text(encoding="ascii") != rows[name]
        ):
            problems.append(f"tests/lifecycle/replay/rows/{name}")
    return problems


def write() -> None:
    text, rows = generate()
    OBLIGATIONS_PATH.write_text(text, encoding="ascii")
    for path in ROWS_DIR.glob(f"{ROW_PREFIX}*.yaml"):
        if path.name not in rows:
            path.unlink()
    for name, content in rows.items():
        (ROWS_DIR / name).write_text(content, encoding="ascii")
